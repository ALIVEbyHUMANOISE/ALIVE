/** `#RGB`, `#RRGGBB` and Android's `#AARRGGBB` all become CSS colours. */
function toCss(hex) {
  const value = hex.trim().replace('#', '')
  const digits =
    value.length === 3
      ? value.split('').map((c) => c + c).join('')
      : value.padStart(6, '0').slice(-6)
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(digits.slice(i, i + 2), 16))
  if (value.length !== 8) return `#${digits}`
  const alpha = parseInt(value.slice(0, 2), 16) / 255
  return `rgba(${r}, ${g}, ${b}, ${Number(alpha.toFixed(2))})`
}

function readColors() {
  const xml = readFileSync(join(res, 'values/colors.xml'), 'utf8')
  const colors = new Map()
  for (const [, name, hex] of xml.matchAll(/<color name="([^"]+)">([^<]+)<\/color>/g)) {
    colors.set(name, toCss(hex))
  }
  return colors
}

/** One `<path>` is one colour: a run of `Mx,yhWvHh-Wz` cells on the grid. */
function readSprite(name, colors) {
  const xml = readFileSync(join(res, `drawable/${name}.xml`), 'utf8')
  const size = Number(xml.match(/android:viewportWidth="(\d+)"/)?.[1] ?? 16)
  const layers = []

  for (const [, fill, data] of xml.matchAll(
    /android:fillColor="([^"]+)"\s+android:pathData="([^"]+)"/g
  )) {
    const colour = fill.startsWith('@color/')
      ? colors.get(fill.slice(7)) ?? '#000'
      : toCss(fill)
    const cells = [...data.matchAll(/M([-\d.]+),([-\d.]+)h([-\d.]+)v([-\d.]+)h(-[\d.]+)z/g)].map(
      (m) => [Number(m[1]), Number(m[2]), Number(m[3]), Number(m[4])]
    )
    if (cells.length) layers.push({ colour, cells })
  }

  return { size, layers }
}

const colors = readColors()
const sprites = Object.fromEntries(
  Object.entries(SPRITES).map(([key, file]) => [key, readSprite(file, colors)])
)

mkdirSync(join(out, 'lib'), { recursive: true })
mkdirSync(join(out, 'app'), { recursive: true })

/** One line per layer, so the generated file stays readable in review. */
function printSprites(byName) {
  const body = Object.entries(byName).map(([name, sprite]) => {
    const layers = sprite.layers
      .map(
        (layer) =>
          `      { colour: '${layer.colour}', cells: [${layer.cells
            .map((cell) => `[${cell.join(', ')}]`)
            .join(', ')}] }`
      )
      .join(',\n')
    return `  ${name}: {\n    size: ${sprite.size},\n    layers: [\n${layers}\n    ]\n  }`
  })
  return `{\n${body.join(',\n')}\n}`
}

writeFileSync(
  join(out, 'lib/sprites.ts'),
  `// Generated by web/scripts/sprites.mjs from app/src/main/res/drawable. Do not edit.
export type Sprite = { size: number; layers: { colour: string; cells: number[][] }[] }

export const sprites = ${printSprites(sprites)} as const

export type SpriteName = keyof typeof sprites
`
)

writeFileSync(
  join(out, 'app/tokens.css'),
  `/* Generated by web/scripts/sprites.mjs from app/src/main/res/values/colors.xml.
   The site's palette is the app's palette; change it there and re-run the script. */
:root {\n${[...colors]
    .map(([name, value]) => `  --alive-${name.replace(/^alive_/, '')}: ${value};`)
    .join('\n')}\n}\n`
)

